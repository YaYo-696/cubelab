import { expect, test } from '@playwright/test';
test('navegación móvil, contenido diferido, persistencia y mezcla offline', async ({ page, context }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/');
    await expect(page.getByRole('heading', { name: 'Timer', exact: true })).toBeVisible();
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    await page.reload();
    await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
    await context.setOffline(true);
    await page.reload();
    await page.getByLabel('Evento').selectOption('222');
    await page.getByRole('button', { name: 'Generar mezcla' }).click();
    await expect(page.getByText('Mezcla generada con criterios WCA')).toBeVisible({ timeout: 60000 });
    await page.getByRole('link', { name: 'Academia' }).click();
    await page.getByRole('button', { name: 'Abrir' }).click();
    await expect(page.getByRole('heading', { name: 'Giro de la cara derecha' })).toBeVisible();
    await page.getByRole('link', { name: 'Ajustes' }).click();
    await page.getByLabel('Idioma').selectOption('en');
    await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible();
    await page.reload();
    await expect(page.getByLabel('Language')).toHaveValue('en');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
